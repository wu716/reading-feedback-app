const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(process.env.PLAYWRIGHT_PACKAGE||'playwright');
const root=path.resolve(__dirname,'..');
const task={id:4,text:'整理访谈',parent_id:null,children:[],expected_result:'',completion_basis:'',core_selected:false};
let browser;
(async()=>{
  browser=await chromium.launch({channel:process.env.PLAYWRIGHT_CHANNEL||'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:390,height:844}});
  const errors=[],calls=[],drafts=new Map();page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>localStorage.setItem('authToken','synthetic-only'));
  await page.route('http://shuran.test/**',async route=>{
    const req=route.request(),url=new URL(req.url()),method=req.method(),body=req.postDataJSON();
    const json=value=>route.fulfill({contentType:'application/json',body:JSON.stringify(value)});
    if(url.pathname==='/return')return route.fulfill({contentType:'text/html',body:'<h1>原页面</h1>'});
    if(url.pathname.startsWith('/static/')){const file=path.join(root,url.pathname.slice(1));const type=file.endsWith('.js')?'application/javascript':file.endsWith('.css')?'text/css':'text/html';return route.fulfill({contentType:type,body:fs.readFileSync(file)});}
    if(url.pathname.startsWith('/api/editor-drafts/')){const key=decodeURIComponent(url.pathname.split('/').at(-1));if(method==='GET')return json({content:drafts.get(key)||{}});if(method==='PUT'){drafts.set(key,body.content);return json({saved:true});}drafts.delete(key);return json({deleted:true});}
    if(method!=='GET')calls.push({path:url.pathname,method,body});
    if(url.pathname==='/api/schedule')return json({date:'2026-11-08',tasks:[task]});
    if(url.pathname==='/api/schedule/tasks/4'&&method==='PATCH'){Object.assign(task,body);return json({tasks:[task]});}
    if(url.pathname==='/api/projects/practice/tasks/daily/4')return json({id:4,kind:'daily',title:task.text,recorded_minutes:30,original_estimate:60,completed:false,feedback:{},history:[]});
    if(url.pathname.endsWith('/feedback')||url.pathname.endsWith('/progress')||url.pathname.endsWith('/rehearsal'))return json({saved:true});
    if(url.pathname==='/api/projects/readiness/daily/4')return json({summary:'可开始',conditions:[]});
    if(url.pathname==='/api/projects/overview')return json({projects:[]});
    if(url.pathname==='/api/projects/conditions/daily/4/history')return json({items:[]});
    if(url.pathname==='/api/projects/commitments/projects/1')return json({current_stage_id:7,commitment:null,draft:null,scope:{tasks:[],outcome:''},history:[],adjustments:[]});
    if(url.pathname==='/api/projects/commitments/stages/7/draft')return json({revision:1,statement:body.statement});
    throw new Error('Unexpected '+method+' '+url.pathname);
  });
  const editor=(type,extra='')=>`http://shuran.test/static/content-editor.html?type=${type}&${extra}return=${encodeURIComponent('http://shuran.test/return')}`;
  await page.goto(editor('expectation','day=2026-11-08&'),{waitUntil:'domcontentloaded'});
  await page.locator('[name=expected_result]').fill('形成五个问题');
  await page.locator('#editorBack').click();await page.waitForURL('**/return');
  assert.equal(drafts.get('task-new:2026-11-08').expected_result,'形成五个问题');
  await page.goto(editor('expectation','day=2026-11-08&'),{waitUntil:'domcontentloaded'});
  assert.equal(await page.locator('[name=expected_result]').inputValue(),'形成五个问题');
  await page.goto(editor('expectation','id=4&day=2026-11-08&'),{waitUntil:'domcontentloaded'});
  await page.locator('[name=completion_basis]').fill('可以直接访谈');
  await page.getByRole('button',{name:'保存任务内容'}).click();await page.waitForURL('**/return');
  assert.equal(task.completion_basis,'可以直接访谈');
  await page.goto(editor('feedback','kind=daily&id=4&day=2026-11-08&'),{waitUntil:'domcontentloaded'});
  await page.locator('#contentForm').waitFor();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Feedback page must fit a 390px phone');
  await page.locator('[name=outcome]').fill('写出了提纲');await page.locator('[name=advanced]').fill('整理访谈主题');
  await page.getByRole('button',{name:'保存结果与用时反馈'}).click();await page.waitForURL('**/return');
  assert(calls.some(c=>c.path.endsWith('/feedback')&&c.body.outcome==='写出了提纲'));
  assert(calls.some(c=>c.path.endsWith('/progress')&&c.body.advanced==='整理访谈主题'));
  await page.goto(editor('rehearsal','kind=daily&id=4&'),{waitUntil:'domcontentloaded'});
  await page.locator('[name=first_step]').fill('列出问题');
  await page.getByRole('button',{name:'保存预演'}).click();await page.waitForURL('**/return');
  assert(calls.some(c=>c.path.endsWith('/rehearsal')&&c.body.first_step==='列出问题'));
  await page.goto(editor('condition','kind=daily&id=4&'),{waitUntil:'domcontentloaded'});
  await page.locator('[data-create-condition]').waitFor({state:'attached'});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Condition page must fit a 390px phone');
  assert.equal(await page.locator('[data-create-condition] [name=strength]').count(),1);
  assert.equal(await page.locator('[data-create-condition] [name=check_at]').count(),1);
  await page.locator('.condition-create summary').click();
  await page.locator('[data-create-condition] [name=title]').fill('收到确认');
  await page.locator('#editorBack').click();await page.waitForURL('**/return');
  await page.goto(editor('condition','kind=daily&id=4&'),{waitUntil:'domcontentloaded'});
  await page.locator('.condition-create summary').click();
  assert.equal(await page.locator('[data-create-condition] [name=title]').inputValue(),'收到确认');
  await page.goto(editor('commitment','id=1&'),{waitUntil:'domcontentloaded'});
  assert.equal(await page.locator('[data-commitment-form] [name=statement]').count(),1);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:11,errors}));
  await browser.close();
})().catch(async e=>{console.error(e);await browser?.close();process.exitCode=1;});
